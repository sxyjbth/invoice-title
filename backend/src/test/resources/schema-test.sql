DROP TABLE IF EXISTS invoice_import_task;
DROP TABLE IF EXISTS invoice_operation_log;
DROP TABLE IF EXISTS invoice_title_version;
DROP TABLE IF EXISTS subject_department_employee_exclusion;
DROP TABLE IF EXISTS subject_permission;
