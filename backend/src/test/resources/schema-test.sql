);

CREATE TABLE invoice_operation_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_type VARCHAR(30) NOT NULL,
    operation_type VARCHAR(30) NOT NULL,
    business_id VARCHAR(64) NOT NULL,
    business_name VARCHAR(200),
    detail_json VARCHAR(2000),
    result VARCHAR(20) NOT NULL,
    operator_user_id VARCHAR(100) NOT NULL,
    operator_name VARCHAR(100) NOT NULL,
    client_ip VARCHAR(64),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE invoice_import_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no VARCHAR(40) NOT NULL UNIQUE,
    original_file_name VARCHAR(255) NOT NULL,
    storage_provider VARCHAR(20) NOT NULL,
    storage_key VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_count INT NOT NULL DEFAULT 0,
    success_count INT NOT NULL DEFAULT 0,
    failure_count INT NOT NULL DEFAULT 0,
    error_file_key VARCHAR(500),
    started_at TIMESTAMP,
    finished_at TIMESTAMP,
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE invoice_import_row_error (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    row_no INT NOT NULL,
    taxpayer_id VARCHAR(32),
    error_code VARCHAR(50) NOT NULL,
    error_message VARCHAR(500) NOT NULL,
    raw_data_json VARCHAR(4000),
    created_at TIMESTAMP NOT NULL
);
